// Writes the master timeline to audio/cues.json so the soundtrack is cut to the same cues,
// the voice-over lines (subtitle text + duration) to src/vo-lines.js for the burned-in subtitles,
// and the same subtitles as a sidecar file, out/jagermeister-the-drop.en.srt.
import fs from 'node:fs';
import { CUE, FPS, DURATION } from '../src/timeline.js';
const at = (p) => new URL(p, import.meta.url);
fs.writeFileSync(at('../audio/cues.json'), JSON.stringify({ ...CUE, FPS, DURATION }, null, 2));
const lines = JSON.parse(fs.readFileSync(at('../audio/vo/lines.json'), 'utf8'));
const vo = Object.fromEntries(Object.entries(lines).map(([k, v]) => [k, { sub: v.sub, dur: v.dur }]));
fs.writeFileSync(at('../src/vo-lines.js'), `// generated by render/export-cues.mjs from audio/vo/lines.json\nexport const VO = ${JSON.stringify(vo, null, 2)};\n`);

// same timing as Overlay.subtitles()
const keys = Object.keys(CUE.vo).sort((a, b) => CUE.vo[a] - CUE.vo[b]);
const ts = (t) => {
  const ms = Math.round(t * 1000);
  const p = (n, w = 2) => String(n).padStart(w, '0');
  return `${p(Math.floor(ms / 3600000))}:${p(Math.floor(ms / 60000) % 60)}:${p(Math.floor(ms / 1000) % 60)},${p(ms % 1000, 3)}`;
};
const srt = keys.map((k, i) => {
  const t0 = CUE.vo[k] - 0.05;
  const next = i + 1 < keys.length ? CUE.vo[keys[i + 1]] - 0.1 : 1e9;
  const t1 = Math.min(CUE.vo[k] + vo[k].dur + 0.45, next);
  return `${i + 1}\n${ts(t0)} --> ${ts(t1)}\n${vo[k].sub}\n`;
});
fs.mkdirSync(at('../out/'), { recursive: true });
fs.writeFileSync(at('../out/jagermeister-the-drop.en.srt'), srt.join('\n'));
console.log('audio/cues.json, src/vo-lines.js and out/jagermeister-the-drop.en.srt written');
